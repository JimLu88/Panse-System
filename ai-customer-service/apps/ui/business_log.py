"""
将后台日志转写为业务可读文案（控制台不向用户暴露底层术语）。
"""

from __future__ import annotations

import re


def humanize_log_line(raw: str) -> str:
    s = (raw or "").strip()
    if not s:
        return ""

    # 常见句式替换（顺序 matters：先长后短）
    reps: list[tuple[str, str]] = [
        (r"\[Brain\]\s*Brain 已恢复自动接待", "自动接待已从暂停中恢复。"),
        (r"\[Brain\]\s*Brain 本轮开始 trigger=audio_peak", "检测到提示音，开始本轮接待流程。"),
        (r"\[Brain\]\s*Brain 本轮开始 trigger=visual_scan", "看到会话列表有变化，开始本轮接待流程。"),
        (r"\[Brain\]\s*Brain 本轮开始 trigger=sweep_fallback", "定时检查：开始扫描是否有新会话。"),
        (r"\[Brain\]\s*Brain 本轮开始 trigger=(\S+)", r"开始本轮接待（来源：\1）。"),
        (r"视觉哨兵：已启用.*", "已开启视觉哨兵：每隔几秒自动检查会话列表。"),
        (r"视觉哨兵：检测到会话列表变化.*", "看到会话列表有新动静，开始一轮接待检查。"),
        (r"视觉哨兵：未配置 session_list_rect.*", "视觉哨兵未启用：请先在「千牛屏幕坐标校准」里录左侧会话列表区域。"),
        (r"AI 陪伴：已打开.*对话。", "AI 陪伴：对话窗口已打开。"),
        (r"AI 陪伴：简短摘要已生成.*", "AI 陪伴：会话摘要已保存，下次将自动加载。"),
        (r"AI 陪伴：已提交追问.*", "AI 陪伴：正在根据你的描述回复…"),
        (r"AI 陪伴：正在生成完整 Plan.*", "AI 陪伴：正在生成完整实施计划…"),
        (r"AI 陪伴：完整 Plan 已生成。", "AI 陪伴：完整实施计划已生成，可复制。"),
        (r"截图里未识别到对方留言，跳过本轮", "窗口已处理，但截图里没看到对方文字，本轮跳过。"),
        (r"标题 OCR 未命中本店.*", "任务栏恢复后标题未认出本店，已尝试把千牛置前。"),
        (r"标题 OCR 命中展示名：", "标题已认出本店（展示名）："),
        (r"标题 OCR 命中店铺代码：", "标题已认出本店（代码）："),
        (
            r"ManualHold：跳过自动回复（千牛已尝试置前/点选会话）",
            "当前为人工接管：已尝试弹出千牛，但不会自动发话；请点「恢复 AI 托管」后继续自动接待。",
        ),
        (r"ManualHold：跳过自动回复", "当前由人工接管，已跳过自动回复。"),
        (r"Jim 介入：", "需要您介入："),
        (r"已排队：恢复 AI 托管.*", "已排队：恢复由系统自动接待。"),
        (r"已入队.*条", "已生成回复并排队发送。"),
        (r"听觉流水线已停止", "消息监听与定时检查已停止。"),
        (r"听觉流水线已启动：.*", "已开始监听新消息并定时检查会话。"),
        (r"【本地数据库消息源】还没配好.*", ""),  # 多行原文已面向用户，见 passthrough
        (r"【本地数据库消息源】找不到千牛.*", ""),
        (r"【本地数据库消息源】已接通.*", "已从千牛聊天记录库读取新消息（不再截图识别）。"),
        (r"正在监听文件：", "数据库文件："),
        (r"当前消息来源：千牛本地聊天记录库.*", "已切换为：读千牛本地聊天记录。"),
        (r"当前消息来源：截图识别.*", "已切换为：听提示音并截图识别。"),
        (r"消息输入已切回 OCR.*", "已改回：听提示音并截图识别。"),
        (r"已打开「千牛 DB 配置向导」.*", "已打开配置向导窗口，请按窗口提示操作。"),
        (r"本地 DB 监听未启动.*", ""),  # 旧文案兼容
        (r"Core 已启动.*", "连接就绪，可以开始接待。"),
        (r"Core 已停止", "接待连接已断开。"),
        (r"弹窗清理：已启用.*", "已开启：尝试自动关闭干扰弹窗。"),
        (r"弹窗清理未启用.*", "自动关弹窗未开启（可在本页勾选后重启监听）。"),
        (r"策略已保存.*", "本页设置已保存。"),
        (r"跳过本轮：上一轮尚未结束", "上一条还在处理中，本条稍后。"),
        (r"判定为广告/系统噪声风格，跳过回复", "识别为系统提示类内容，未自动回复。"),
        (r"模型置信度 .*", "对您这句话把握不足，已转人工并发送安抚话术。"),
        (r"知识库未命中\(硬阈值\)", "知识库里暂时没有匹配话术，已转人工处理。"),
        (r"全自动客服未启动|全自动客服运行中|监听未开", ""),  # 走状态栏，避免刷屏
    ]
    for pat, sub in reps:
        if sub == "":
            if re.search(pat, s):
                return ""
        s = re.sub(pat, sub, s, flags=re.DOTALL)

    # 以下消息已面向用户，直接透传（剥 [Brain] 前缀即可）
    _passthrough_keywords = (
        "听觉诊断：",
        "步骤",
        "置前",
        "千牛已确认",
        "千牛仍未",
        "置前诊断",
        "置前失败",
        "HWND",
        "任务栏",
        "任务栏环境",
        "任务栏点击",
        "任务栏坐标",
        "坐标说明",
        "坐标校验",
        "话术库",
        "兜底原因",
        "步骤5提示",
        "步骤2：",
        "未读会话",
        "视觉哨兵",
        "托管启动",
        "非有效买家",
        "仅建基线",
        "发送成功",
        "发送失败",
        "执行器",
        "致命",
        "异常崩溃",
        "心跳：",
        "触发器收到事件",
        "【本地数据库",
        "请这样操作",
        "在配好之前",
        "常见原因",
        "您勾选了",
        "还差这几项",
        "在此之前请",
        "SOOTHE_WAIT",
        "SEND_TEXT",
        "EXEC ",
        "BLOCK ",
        "buyer_text=",
        "switched=",
    )
    if any(kw in s for kw in _passthrough_keywords):
        s = re.sub(r"^\[Brain\]\s*", "", s).strip()
        return s if s else "（内部操作）"

    # 兜底：去掉常见违禁技术词（万一后端仍带出）
    # 注意：必须先替换长串 "[Brain]" 再替换子串 "Brain"，否则 "Brain" 先被去掉后 "[Brain]" 变成 "[]" 无法再匹配
    banned = (
        "[Brain]",
        "YAML",
        "Core",
        "SequentialExecutor",
        "DryRun",
        "REACQUIRE_CONTEXT",
        "OCR",
        "LLM",
        "SEND_TEXT",
        "Pipeline",
        "Brain",
    )
    low = s
    for b in banned:
        low = low.replace(b, "").replace(b.lower(), "")
    s = low.strip()
    # 清理多余空格
    s = re.sub(r"\s+", " ", s)
    if not s:
        return "已完成一步后台操作。"
    return s
